CREATE TABLE doadores (
    id_doador BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    cpf_cnpj VARCHAR(18) NOT NULL UNIQUE,
    email VARCHAR(150) NOT NULL UNIQUE,
    telefone VARCHAR(20),
    endereco VARCHAR(255),
    tipo_pessoa CHAR(1) NOT NULL CHECK (tipo_pessoa IN ('F', 'J')),
    data_cadastro DATE NOT NULL
);

CREATE INDEX idx_doadores_cpf_cnpj ON doadores(cpf_cnpj);
CREATE INDEX idx_doadores_email ON doadores(email);
CREATE INDEX idx_doadores_nome ON doadores(nome);