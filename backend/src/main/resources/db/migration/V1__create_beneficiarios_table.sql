-- Migration V1: criação da tabela de beneficiários
-- Chave primária no padrão da disciplina: id_<entidade>
CREATE TABLE beneficiarios (
    id_beneficiario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    cpf VARCHAR(14) NOT NULL UNIQUE,
    telefone VARCHAR(20),
    endereco VARCHAR(255),
    situacao_vulnerabilidade VARCHAR(500),
    data_cadastro DATE NOT NULL
);
